import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
const storage = vi.hoisted(() => ({ data: new Map<string, string>() }));
vi.mock('@/lib/post-studio/storage', () => ({ default: { getItem: async (key: string) => storage.data.get(key) ?? null, setItem: async (key: string, value: string) => { storage.data.set(key, value); } } }));
vi.mock('@/components/admin/post-studio/StudioMediaModal', () => ({ default: () => null }));
vi.mock('@/components/admin/post-studio/InstagramPreviewModal', () => ({ default: () => null }));
import HistoryStudio from '@/components/admin/post-studio/HistoryStudio';
import HistoryInspector from '@/components/admin/post-studio/HistoryInspector';
import PostEditor from '@/components/admin/post-studio/PostEditor';
import PromptCreationModal from '@/components/admin/post-studio/PromptCreationModal';
import { Artwork } from '@/components/admin/post-studio/Artwork';
import { createHistoryDesign } from '@/lib/post-studio/history-design';
import { createDraft, listDrafts, readDraft } from '@/lib/post-studio/drafts';
import { historyTemplateIds } from '@/lib/post-studio/history-catalog';
const clipboard = vi.fn().mockResolvedValue(undefined);
beforeEach(() => {
    storage.data.clear(); clipboard.mockReset().mockResolvedValue(undefined);
    vi.stubGlobal('ResizeObserver', class { observe() {} disconnect() {} });
    Object.defineProperty(document, 'fonts', { configurable: true, value: { ready: Promise.resolve() } });
    Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: clipboard } });
    Object.defineProperty(HTMLDialogElement.prototype, 'showModal', { configurable: true, value() { this.open = true; } });
    Object.defineProperty(HTMLDialogElement.prototype, 'close', { configurable: true, value() { this.open = false; } });
});
afterEach(() => { cleanup(); vi.unstubAllGlobals(); });
describe('History creation and editing', () => {
    it('shows one story design and creates a blank cover in the chosen language and size', async () => {
        const open = vi.fn(); render(<HistoryStudio scope="history-test" onBack={vi.fn()} onOpenDraft={open} />);
        expect(screen.queryByLabelText('History post type')).not.toBeInTheDocument();
        expect(screen.getByText('1. Main page')).toBeInTheDocument();
        expect(screen.getByText('2. Paragraph page · optional')).toBeInTheDocument();
        fireEvent.change(screen.getByLabelText('Language'), { target: { value: 'ne' } });
        fireEvent.change(screen.getByLabelText('Canvas size'), { target: { value: 'story' } });
        fireEvent.click(screen.getByRole('button', { name: 'Start blank story' }));
        await waitFor(() => expect(open).toHaveBeenCalledOnce());
        const [draft] = await listDrafts('history-test');
        expect(draft.design).toMatchObject({ template: 'history', format: 'story', summary: '', history: { language: 'ne', pageKind: 'cover', sample: false, subject: '', year: '', fact: '' } });
    });
    it('passes the selected template and publication date into a history-only prompt', async () => {
        render(<HistoryStudio scope="history-test" onBack={vi.fn()} onOpenDraft={vi.fn()} />);
        fireEvent.change(screen.getByLabelText('Publication date · Nepal'), { target: { value: '2026-03-04' } });
        fireEvent.click(screen.getByRole('button', { name: 'New history post' }));
        fireEvent.click(screen.getByRole('button', { name: 'Copy Post Prompt' }));
        await waitFor(() => expect(clipboard).toHaveBeenCalledOnce());
        const prompt = clipboard.mock.calls[0][0];
        expect(prompt).toContain('FOUR Today in History editions');
        expect(prompt).toContain('PUBLICATION DATE: 2026-03-04');
        expect(prompt).toContain('ONE national event from Nepal');
        expect(screen.queryByLabelText('Featured team')).not.toBeInTheDocument();
    });
    it('reviews missing event facts and saves the AI response without sample data', async () => {
        const open = vi.fn();
        render(<PromptCreationModal scope="history-test" initialKind="history" initialOptions={{ template: 'on-this-day', historyDate: '2026-07-18' }} onClose={vi.fn()} onOpen={open} />);
        fireEvent.click(screen.getByRole('button', { name: 'Next: Paste AI Output' }));
        const national = { template: 'on-this-day', scope: 'national', headline: 'Nepal test event', data: { year: '1918 B.S.', dateLabel: 'Nepali month/day (B.S.)', subject: 'Nepal test event' } };
        const international = { template: 'on-this-day', scope: 'international', headline: 'International test event', data: { year: '1900', dateLabel: '18 JULY', subject: 'International test event', fact: 'Illustrative test fixture.' }, sources: ['https://example.org/archive'] };
        fireEvent.change(screen.getByLabelText('AI response'), { target: { value: JSON.stringify({ posts: [{ ...national, language: 'ne' }, { ...national, language: 'en', data: { ...national.data, fact: 'National test context.' } }, { ...international, language: 'en' }, { ...international, language: 'ne' }] }) } });
        fireEvent.click(screen.getByRole('button', { name: 'Review post' }));
        fireEvent.change(screen.getByLabelText('Cover context'), { target: { value: 'Confirmed context for the Nepal test event.' } });
        fireEvent.click(screen.getByRole('button', { name: 'Create 4 posts' }));
        await waitFor(() => expect(open).toHaveBeenCalledOnce());
        const draft = open.mock.calls[0][0];
        expect(draft.design.history).toMatchObject({ template: 'on-this-day', year: '1918 B.S.', subject: 'Nepal test event', role: '', lifespan: '', sample: false });
        expect(draft.design.cricket).toBeUndefined();
        const saved = await listDrafts('history-test');
        expect(saved).toHaveLength(4);
        expect(new Set(saved.map(item => item.carouselId)).size).toBe(1);
        expect(saved.map(item => item.carouselOrder).sort()).toEqual([0, 1, 2, 3]);
        expect(saved.map(item => item.design.history?.storyScope).sort()).toEqual(['international', 'international', 'national', 'national']);
        cleanup();
        render(<PostEditor scope="history-test" draft={draft} onClose={vi.fn()} />);
        await screen.findByText('Page 1 of 4');
        await waitFor(() => expect(screen.getByRole('button', { name: 'Next page' })).toBeEnabled());
        fireEvent.click(screen.getByRole('button', { name: 'Page 3: International test event' }));
        await screen.findByText('Page 3 of 4');
        expect(screen.getByLabelText('Subject')).toHaveValue('International test event');
        expect(screen.getByLabelText('History language')).toHaveValue('en');
        fireEvent.click(screen.getByRole('button', { name: 'Page 4: International test event' }));
        await screen.findByText('Page 4 of 4');
        expect(screen.getByLabelText('History language')).toHaveValue('ne');

    });
    it('preserves authored copy when changing the event language', () => {
        const design = { ...createHistoryDesign('on-this-day'), headline: 'An editor’s own headline' }, change = vi.fn();
        render(<HistoryInspector design={design} onChange={change} />);
        expect(screen.queryByLabelText('History template')).not.toBeInTheDocument();
        fireEvent.change(screen.getByLabelText('History language'), { target: { value: 'ne' } });
        expect(change.mock.calls[0][0](design)).toMatchObject({ headline: 'An editor’s own headline', history: { language: 'ne' } });
    });
    for (const id of historyTemplateIds) it(`routes ${id} to the history artwork`, () => {
        render(<Artwork design={createHistoryDesign(id)} />);
        expect(screen.getByTestId('post-artwork')).toHaveAttribute('data-history-template', 'on-this-day');
        expect(screen.getByTestId('post-artwork')).toHaveAttribute('data-export-error', '');
        expect(screen.queryByText('NPL 2026')).not.toBeInTheDocument();
        expect(screen.getByTestId('history-watermark')).toBeInTheDocument();
        expect(screen.getByTestId('echo11-promotion')).toBeInTheDocument();
        expect(screen.getByRole('link', { name: /echo11.tech/ })).toBeInTheDocument();
        expect(screen.getByText('echo11.labs@gmail.com')).toBeInTheDocument();
        expect(screen.getByAltText('echo11 logo')).toHaveAttribute('src', '/studio/echo11-logo.svg');
        expect(screen.getAllByText('TODAY IN HISTORY')).toHaveLength(2);
        expect(screen.queryByTestId('history-seal')).not.toBeInTheDocument();
    });
    it('opens the event inspector and saves edits through the actual editor', async () => {
        const draft = await createDraft('history-test', 'History draft', createHistoryDesign('born'));
        render(<PostEditor scope="history-test" draft={draft} onClose={vi.fn()} />);
        await waitFor(() => expect(screen.getByLabelText('History language')).toBeEnabled());
        fireEvent.change(screen.getByLabelText('Subject'), { target: { value: 'Edited person' } });
        fireEvent.click(screen.getByRole('button', { name: 'Save changes' }));
        await waitFor(() => expect(screen.getByRole('button', { name: 'Save changes' })).toHaveTextContent('Saved'));
        expect((await readDraft('history-test', draft.id))?.design.history?.subject).toBe('Edited person');
    });
    it('opens both main pages from a previously split History import and saves them as one carousel', async () => {
        const base = 'prompt-22222222-2222-4222-8222-222222222222';
        const national = createHistoryDesign('on-this-day'); national.history!.storyScope = 'national';
        const international = createHistoryDesign('on-this-day'); international.history!.storyScope = 'international';
        international.headline = 'Recovered international story';
        international.history!.subject = 'International subject';
        const first = await createDraft('history-test', 'National', national, { carouselId: `${base}-national`, carouselOrder: 0 });
        const second = await createDraft('history-test', 'International', international, { carouselId: `${base}-international`, carouselOrder: 0 });
        render(<PostEditor scope="history-test" draft={first} onClose={vi.fn()} />);
        await screen.findByText('Page 1 of 2');
        await waitFor(() => expect(screen.getByRole('button', { name: 'Next page' })).toBeEnabled());
        fireEvent.click(screen.getByRole('button', { name: 'Page 2: Recovered international story' }));
        await screen.findByText('Page 2 of 2');
        expect(screen.getByLabelText('Subject')).toHaveValue('International subject');
        fireEvent.click(screen.getByRole('button', { name: 'Save changes' }));
        await waitFor(() => expect(screen.getByRole('button', { name: 'Save changes' })).toHaveTextContent('Saved'));
        expect((await readDraft('history-test', first.id))?.carouselId).toBe(base);
        expect((await readDraft('history-test', second.id))?.carouselId).toBe(base);
    });
    it('copies the selected post caption without other editions or carousel counts', async () => {
        const first = createHistoryDesign('on-this-day'); first.headline = 'National headline'; first.history!.fact = 'National event context.';
        const second = createHistoryDesign('on-this-day'); second.headline = 'International headline'; second.history!.fact = 'International event context.';
        const start = await createDraft('history-test', 'Caption story · 1/2', first, { carouselId: 'caption-story', carouselOrder: 0 });
        await createDraft('history-test', 'Caption story · 2/2', second, { carouselId: 'caption-story', carouselOrder: 1 });
        render(<PostEditor scope="history-test" draft={start} onClose={vi.fn()} />);
        await screen.findByText('Page 1 of 2');
        await waitFor(() => expect(screen.getByRole('button', { name: 'Next page' })).toBeEnabled());
        fireEvent.click(screen.getByRole('button', { name: 'Page 2: International headline' }));
        fireEvent.click(screen.getByRole('tab', { name: /^Pages/ }));
        fireEvent.click(screen.getByText('Caption & export'));
        fireEvent.click(screen.getByRole('button', { name: 'Copy this post’s caption' }));
        await waitFor(() => expect(clipboard).toHaveBeenCalledOnce());
        const caption = clipboard.mock.calls[0][0];
        expect(caption).toContain('International headline');
        expect(caption).toContain('International event context.');
        expect(caption).not.toContain('National headline');
        expect(caption).not.toContain('CAROUSEL BREAKDOWN');
        expect(caption).not.toContain('2/2');
    });
    it('adds a paragraph page through the editor instead of another cover', async () => {
        const draft = await createDraft('history-test', 'History story', createHistoryDesign('on-this-day'));
        render(<PostEditor scope="history-test" draft={draft} onClose={vi.fn()} />);
        await waitFor(() => expect(screen.getByLabelText('History language')).toBeEnabled());
        fireEvent.click(screen.getByRole('button', { name: 'Add page' }));
        await screen.findByLabelText('Paragraph text');
        fireEvent.click(screen.getByRole('button', { name: 'Select summary' }));
        expect(screen.getByLabelText('Paragraph text')).toBeInTheDocument();
        const drafts = await listDrafts('history-test');
        expect(drafts).toHaveLength(2);
        expect(drafts.find(item => item.id !== draft.id)?.design.history).toMatchObject({ pageKind: 'paragraph', body: '', year: '1816' });
    });
});
